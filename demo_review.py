"""Deterministic, OFFLINE comparison exercise for the bundled synthetic TXT ONLY.

This is NOT an AI model. It makes no network request and cannot be used with a
user-supplied or real application. The regular, optional LLM integration is
separate (ai_review.py).
"""
import hashlib
import json
from pathlib import Path

from ai_review import compare_ai
from parser import parse_application

ROOT = Path(__file__).resolve().parent
DEMO_FILE = ROOT / 'samples' / 'sample_application.txt'


def compare_synthetic_demo(document_content, lines, local_values, allowed_keys):
    original = DEMO_FILE.read_bytes()
    if hashlib.sha256(document_content).digest() != hashlib.sha256(original).digest():
        raise ValueError('모의 비교는 제공된 samples/sample_application.txt 파일에서만 실행할 수 있습니다. 실제 신청서는 사용할 수 없습니다.')

    # The proposal is reconstructed from the fixture's rule-based original, not
    # generated by a model. Edited current values make real comparison scenarios.
    _, expected, citations, _, _ = parse_application(DEMO_FILE.name, original, allowed_keys, False)
    fields = {}
    source_lines = {}
    for key, val in expected.items():
        item = citations.get(key) or {}
        n = item.get('line')
        if n is not None and any(row.get('n') == n for row in lines):
            fields[key] = val
            source_lines[key] = [n]

    def fixture_transport(_payload):
        # No external call; the fixture is immediately returned in memory.
        return {'choices': [{'message': {'content': json.dumps(
            {'fields': fields, 'source_lines': source_lines}, ensure_ascii=False)}}]}

    result = compare_ai(
        lines, local_values, allowed_keys,
        config={'available': True, 'model': '모의 응답 · 실제 AI 아님',
                'mode': 'local', 'base_url': 'http://127.0.0.1/unused'},
        transport=fixture_transport,
    )
    result['mode'] = 'demo'
    for candidate in result['suggestions'].values():
        candidate['source']['method'] = '모의 비교 제안 (실제 AI 아님)'
    result['notice'] = ('이 비교표는 합성 예제로 생성한 모의 응답입니다. 실제 LLM을 호출하지 않았으며 '
                        'AI 정확도나 모델 성능을 나타내지 않습니다. 출처 확인·선택 반영·사건 저장 기능 검증에만 사용하세요.')
    return result
